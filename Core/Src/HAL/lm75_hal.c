#include "lm75_hal.h"
#include "i2c.h"

/* 私有宏 ------------------------------------------------------------*/
#define LM75_REG_TEMP  0x00

/* 导出的函数 --------------------------------------------------------*/

/**
 * @brief  初始化LM75传感器
 */
void LM75_HAL_Init(void)
{
    // 软件I2C已在GPIO初始化时配置，无需额外操作
}

/**
 * @brief  读取LM75温度
 * @retval 温度值(°C)，支持负温度
 */
float LM75_HAL_ReadTemp(void)
{
    int16_t raw = (int16_t)TMP75_Read_2Byte(LM75_REG_TEMP);
    if (raw & 0x8000) {
        raw = ~(raw - 1);
        return -(float)raw / 256.0f;
    }
    return (float)raw / 256.0f;
}
